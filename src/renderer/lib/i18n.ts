export function describeError(e: { code?: string; detail?: string; data?: Record<string, unknown> } | undefined): string {
  if (!e) return errorMessage('UNKNOWN');
  if (e.code === 'VALIDATION' || e.code === 'CONFLICT') {
    const tpl = (lang === 'en' ? VALIDATION_EN : VALIDATION_DETAIL)[e.detail ?? ''];
    if (tpl) {
      return tpl.replace(/\{(\w+)\}/g, (_m, k: string) => {
        const v = e.data?.[k];
        return Array.isArray(v) ? v.join(' ') : String(v ?? '');
      });
    }
  }
  if (e.code === 'DISK_FULL' && typeof e.data?.needed === 'number') {
    return `${errorMessage('DISK_FULL')} (${lang === 'en' ? 'needed' : 'necesario'}: ${Math.ceil(Number(e.data.needed) / 1048576)} MB)`;
  }
  return errorMessage(e.code);
}
