export function t(s: string, params?: Record<string, string | number>): string {
  let out = lang === 'en' ? EN[s] ?? s : s;
  if (params) out = out.replace(/\{(\w+)\}/g, (m, k: string) => (k in params ? String(params[k]) : m));
  return out;
}

